-- 子代理表
CREATE TABLE IF NOT EXISTS sub_agent (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid VARCHAR(64),
    tenant_id BIGINT NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN DEFAULT FALSE NOT NULL,

    -- 子代理基本信息
    sub_agent_code VARCHAR(128) NOT NULL,
    sub_agent_name VARCHAR(255) NOT NULL,

    -- 父任务信息
    parent_task_id BIGINT NOT NULL,
    parent_run_id BIGINT,

    -- 关联的 Agent
    agent_id BIGINT,
    agent_version_id BIGINT,

    -- 任务描述
    task_description TEXT NOT NULL,

    -- 执行状态
    status VARCHAR(64) DEFAULT 'pending',  -- pending, running, completed, failed, cancelled

    -- 执行结果
    result TEXT,
    error_message TEXT,

    -- 执行时间
    start_time TIMESTAMP WITH TIME ZONE,
    end_time TIMESTAMP WITH TIME ZONE,

    -- Token 使用量
    token_usage INTEGER DEFAULT 0,

    -- 执行配置
    priority INTEGER DEFAULT 10,  -- 优先级（数字越小优先级越高）
    isolated BOOLEAN DEFAULT TRUE,  -- 是否隔离执行
    timeout_ms BIGINT DEFAULT 300000,  -- 超时时间（毫秒，默认5分钟）

    -- 唯一约束
    CONSTRAINT uk_sub_agent_code UNIQUE (tenant_id, sub_agent_code)
);

-- 索引
CREATE INDEX IF NOT EXISTS idx_sub_agent_tenant ON sub_agent(tenant_id);
CREATE INDEX IF NOT EXISTS idx_sub_agent_parent_task ON sub_agent(parent_task_id);
CREATE INDEX IF NOT EXISTS idx_sub_agent_status ON sub_agent(status);
CREATE INDEX IF NOT EXISTS idx_sub_agent_priority ON sub_agent(priority);

