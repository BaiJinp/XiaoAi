-- 用户身份映射表
CREATE TABLE IF NOT EXISTS user_identity_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid VARCHAR(64),
    tenant_id BIGINT NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN DEFAULT FALSE NOT NULL,

    -- 身份映射信息
    platform_user_id BIGINT NOT NULL,          -- 平台用户ID
    channel_type VARCHAR(64) NOT NULL,         -- 渠道类型（feishu、dingtalk、wechat、web、api）
    channel_user_id VARCHAR(255) NOT NULL,     -- 渠道用户ID
    channel_user_name VARCHAR(255),            -- 渠道用户名

    -- 验证状态
    verification_status VARCHAR(64) DEFAULT 'pending',  -- verified、pending、failed
    last_verified_at TIMESTAMP WITH TIME ZONE,

    -- 状态
    status VARCHAR(64) DEFAULT 'active',  -- active、inactive

    -- 唯一约束
    CONSTRAINT uk_identity_mapping UNIQUE (tenant_id, channel_type, channel_user_id)
);

-- 索引
CREATE INDEX IF NOT EXISTS idx_identity_mapping_platform ON user_identity_mapping(platform_user_id);
CREATE INDEX IF NOT EXISTS idx_identity_mapping_channel ON user_identity_mapping(channel_type, channel_user_id);
CREATE INDEX IF NOT EXISTS idx_identity_mapping_status ON user_identity_mapping(status, verification_status);
