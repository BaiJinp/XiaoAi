-- 对话会话表
CREATE TABLE IF NOT EXISTS conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid VARCHAR(64),
    tenant_id BIGINT NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN DEFAULT FALSE NOT NULL,

    -- 对话基本信息
    conversation_code VARCHAR(64) NOT NULL,
    title VARCHAR(255),
    user_id BIGINT NOT NULL,
    agent_id BIGINT,
    status VARCHAR(64) DEFAULT 'active',  -- active, archived, deleted

    -- 统计信息
    message_count INTEGER DEFAULT 0,
    total_tokens BIGINT DEFAULT 0,
    summary TEXT,

    -- 分支信息
    parent_conversation_id BIGINT,
    branch_point_message_id BIGINT,

    -- 标签和元数据
    tags_json TEXT,
    last_interaction_at TIMESTAMP WITH TIME ZONE,

    -- 唯一约束
    CONSTRAINT uk_conversation_code UNIQUE (tenant_id, conversation_code)
);

-- 对话消息表
CREATE TABLE IF NOT EXISTS conversation_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid VARCHAR(64),
    tenant_id BIGINT NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN DEFAULT FALSE NOT NULL,

    -- 消息基本信息
    message_code VARCHAR(64) NOT NULL,
    conversation_id BIGINT NOT NULL,
    role VARCHAR(32) NOT NULL,  -- user, assistant, system
    content TEXT NOT NULL,
    sequence_number INTEGER NOT NULL,

    -- 分支信息
    parent_message_id BIGINT,

    -- 关联信息
    task_id BIGINT,
    run_id BIGINT,
    token_count INTEGER,

    -- 压缩信息
    compressed BOOLEAN DEFAULT FALSE,
    compressed_content TEXT,

    -- 元数据
    metadata_json TEXT,

    -- 唯一约束
    CONSTRAINT uk_message_code UNIQUE (tenant_id, message_code)
);

-- 索引
CREATE INDEX IF NOT EXISTS idx_conversation_user ON conversation(user_id);
CREATE INDEX IF NOT EXISTS idx_conversation_agent ON conversation(agent_id);
CREATE INDEX IF NOT EXISTS idx_conversation_status ON conversation(status);
CREATE INDEX IF NOT EXISTS idx_conversation_last_interaction ON conversation(last_interaction_at DESC);

CREATE INDEX IF NOT EXISTS idx_message_conversation ON conversation_message(conversation_id);
CREATE INDEX IF NOT EXISTS idx_message_sequence ON conversation_message(conversation_id, sequence_number);
CREATE INDEX IF NOT EXISTS idx_message_role ON conversation_message(role);

-- 全文搜索索引（PostgreSQL）
CREATE INDEX IF NOT EXISTS idx_conversation_summary_fts ON conversation USING gin(to_tsvector('simple', summary));
CREATE INDEX IF NOT EXISTS idx_message_content_fts ON conversation_message USING gin(to_tsvector('simple', content));
