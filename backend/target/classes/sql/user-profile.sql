-- 用户画像表
CREATE TABLE IF NOT EXISTS user_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid VARCHAR(64),
    tenant_id BIGINT NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN DEFAULT FALSE NOT NULL,

    -- 用户和Agent
    user_id BIGINT NOT NULL,
    agent_id BIGINT NOT NULL,

    -- 用户画像信息
    preferences_json TEXT,           -- 用户偏好
    behavior_patterns_json TEXT,      -- 行为模式
    interaction_style_json TEXT,      -- 交互风格
    skill_levels_json TEXT,           -- 技能水平
    favorite_tools_json TEXT,         -- 常用工具
    conversation_summary TEXT,        -- 对话历史摘要

    -- 统计信息
    interaction_count INTEGER DEFAULT 0,
    last_interaction_at TIMESTAMP WITH TIME ZONE,
    version INTEGER DEFAULT 1,
    status VARCHAR(64) DEFAULT 'active',

    -- 唯一约束
    CONSTRAINT uk_user_profile UNIQUE (tenant_id, user_id, agent_id)
);

-- 索引
CREATE INDEX IF NOT EXISTS idx_user_profile_user ON user_profile(user_id);
CREATE INDEX IF NOT EXISTS idx_user_profile_agent ON user_profile(agent_id);
CREATE INDEX IF NOT EXISTS idx_user_profile_status ON user_profile(status);
