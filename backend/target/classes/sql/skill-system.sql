-- 技能表
CREATE TABLE IF NOT EXISTS skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid VARCHAR(64),
    tenant_id BIGINT NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN DEFAULT FALSE NOT NULL,

    -- 技能基本信息
    skill_code VARCHAR(128) NOT NULL,
    skill_name VARCHAR(255) NOT NULL,
    description TEXT,
    skill_type VARCHAR(64) NOT NULL, -- workflow, tool_chain, prompt_template, decision_rule

    -- 触发条件
    trigger_condition_json TEXT,

    -- 技能内容
    content_json TEXT,

    -- 来源
    source_task_id BIGINT,
    created_by_user_id BIGINT,

    -- 使用统计
    usage_count INTEGER DEFAULT 0,
    success_count INTEGER DEFAULT 0,
    success_rate INTEGER DEFAULT 0,
    last_used_at TIMESTAMP WITH TIME ZONE,

    -- 版本和状态
    version INTEGER DEFAULT 1,
    status VARCHAR(64) DEFAULT 'active', -- active, deprecated, archived

    -- 标签
    tags_json TEXT,

    -- 唯一约束
    CONSTRAINT uk_skill_tenant_code UNIQUE (tenant_id, skill_code)
);

-- 索引
CREATE INDEX IF NOT EXISTS idx_skill_tenant ON skill(tenant_id);
CREATE INDEX IF NOT EXISTS idx_skill_type ON skill(skill_type);
CREATE INDEX IF NOT EXISTS idx_skill_status ON skill(status);
CREATE INDEX IF NOT EXISTS idx_skill_usage ON skill(usage_count DESC, success_rate DESC);
CREATE INDEX IF NOT EXISTS idx_skill_source_task ON skill(source_task_id);

-- 技能使用日志表
CREATE TABLE IF NOT EXISTS skill_usage_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid VARCHAR(64),
    tenant_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    skill_id BIGINT NOT NULL,
    task_id BIGINT,
    run_id BIGINT,
    user_id BIGINT,

    success BOOLEAN NOT NULL,
    execution_time_ms INTEGER,
    error_message TEXT,

    context_json TEXT
);

CREATE INDEX IF NOT EXISTS idx_skill_usage_log_skill ON skill_usage_log(skill_id);
CREATE INDEX IF NOT EXISTS idx_skill_usage_log_task ON skill_usage_log(task_id);
CREATE INDEX IF NOT EXISTS idx_skill_usage_log_time ON skill_usage_log(created_at DESC);

