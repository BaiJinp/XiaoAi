-- 上下文文件表
CREATE TABLE IF NOT EXISTS context_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid VARCHAR(64),
    tenant_id BIGINT NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN DEFAULT FALSE NOT NULL,

    -- 文件基本信息
    file_code VARCHAR(128) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    description TEXT,
    content TEXT NOT NULL,  -- Markdown 格式的内容

    -- 文件类型
    file_type VARCHAR(64) DEFAULT 'custom',  -- project, agent, workspace, custom

    -- 关联信息
    project_id BIGINT,  -- 关联的项目ID
    agent_id BIGINT,    -- 关联的 Agent ID
    created_by_user_id BIGINT,

    -- 加载设置
    auto_load BOOLEAN DEFAULT FALSE,  -- 是否自动加载到对话
    priority INTEGER DEFAULT 0,       -- 优先级（数字越大优先级越高）

    -- 标签
    tags_json TEXT,

    -- 状态
    status VARCHAR(64) DEFAULT 'active',  -- active, archived

    -- 唯一约束
    CONSTRAINT uk_context_file_code UNIQUE (tenant_id, file_code)
);

-- 索引
CREATE INDEX IF NOT EXISTS idx_context_file_tenant ON context_file(tenant_id);
CREATE INDEX IF NOT EXISTS idx_context_file_project ON context_file(project_id);
CREATE INDEX IF NOT EXISTS idx_context_file_agent ON context_file(agent_id);
CREATE INDEX IF NOT EXISTS idx_context_file_type ON context_file(file_type);
CREATE INDEX IF NOT EXISTS idx_context_file_auto_load ON context_file(auto_load);
CREATE INDEX IF NOT EXISTS idx_context_file_priority ON context_file(priority DESC);

